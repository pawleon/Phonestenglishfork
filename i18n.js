// Перевод одного фрагмента с фолбэками:
// точный словарь → regex-правила → без хвостовой пунктуации → без ведущего
// тире → по частям « · ». Возвращает null, если ничего не подошло.
const CYR_RE = /[А-ЯЁа-яё]/;
function trPiece(t, depth = 0) {
    if (!t || depth > 3) return null;
    const hit = DICT[t] !== undefined ? DICT[t] : (EXTRA_DICT[t] !== undefined ? EXTRA_DICT[t] : PHRASES[t]);
    if (hit !== undefined) return hit;
    // Правила применяются КУМУЛЯТИВНО (в «1 500 ₽/мес, 10-го числа» срабатывают
    // и /мес, и -го числа); rep === null — спец-обработка ниже
    let out = t, changed = false;
    for (const [re, rep] of RULES) {
        if (rep === null) continue;
        re.lastIndex = 0;
        if (re.test(out)) {
            re.lastIndex = 0;
            out = out.replace(re, rep);
            changed = true;
        }
    }
    if (changed) {
        if (CYR_RE.test(out)) {
            const more = phraseFallback(out);
            if (more !== null) out = more;
            if (CYR_RE.test(out) && out.includes(' · ') && depth < 3) {
                out = out.split(' · ').map(x => { const r = CYR_RE.test(x) ? trPiece(x.trim(), depth + 1) : null; return r !== null ? r : x; }).join(' · ');
            }
        }
        return out;
    }
    // «Строка ▼/▲» (кнопки-тогглы)
    const arrow = t.match(/^(.+?)\s*([▼▲])$/);
    if (arrow) {
        const core = trPiece(arrow[1].trim(), depth + 1);
        if (core !== null) return `${core} ${arrow[2]}`;
    }
    // «Строка.» / «Строка…» — переводим ядро, пунктуацию возвращаем
    const punct = t.match(/^(.*?)([.…!?:]+)$/);
    if (punct && punct[1].trim()) {
        const core = trPiece(punct[1].trim(), depth + 1);
        if (core !== null) return core + punct[2];
    }
    // «, строка» (текст-нода после иконки с ведущей запятой/двоеточием)
    const lead = t.match(/^([,;:]\s*)(.+)$/);
    if (lead) {
        const rest = trPiece(lead[2].trim(), depth + 1);
        if (rest !== null) return lead[1] + rest;
    }
    // «— строка» (текст-нода после иконки)
    const dash = t.match(/^([—–-]\s+)(.+)$/);
    if (dash) {
        const rest = trPiece(dash[2].trim(), depth + 1);
        if (rest !== null) return dash[1] + rest;
    }
    // «(строка)» — переводим содержимое скобок
    const paren = t.match(/^\((.+)\)$/);
    if (paren) {
        const core = trPiece(paren[1].trim(), depth + 1);
        if (core !== null) return `(${core})`;
    }
    // Составная «а · б · в» — переводим каждую часть, непереведённые оставляем
    if (t.includes(' · ')) {
        const parts = t.split(' · ');
        let any = false;
        const out = parts.map(p => {
            const r = trPiece(p.trim(), depth + 1);
            if (r !== null) { any = true; return r; }
            return p.trim();
        });
        if (any) return out.join(' · ');
    }
    return phraseFallback(t);
}

export function tr(s) {
    if (lang() !== 'en') return s;
    const key = String(s ?? '');
    const trimmed = key.trim();
    if (!trimmed) return s;
    const res = trPiece(trimmed);
    if (res !== null) return key.replace(trimmed, res);
    if (trimmed.includes('\n')) {
        const lines = trimmed.split('\n').map(line => {
            const t = line.trim();
            if (!t) return line;
            const r = trPiece(t);
            return r !== null ? line.replace(t, r) : line;
        }).join('\n');
        if (lines !== trimmed) return key.replace(trimmed, lines);
    }
    return s;
}

// ── Перевод отрендеренного DOM ──
// Оригинал хранится на самой ноде (__gpRu), переведённое значение — в __gpEn:
// если приложение потом записало в ноду НОВЫЙ текст, он снова переводится
// (а не откатывается к старому оригиналу). Переключение языков обратимо.
const ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
const CYR = /[А-ЯЁа-яё]/;

export function trDom(root) {
    if (!root) return;
    if (root.nodeType === 3) root = root.parentElement;
    if (!root) return;
    const en = lang() === 'en';
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    let node;
    while ((node = walker.nextNode())) {
        const parent = node.parentElement;
        if (!parent || parent.tagName === 'SCRIPT' || parent.tagName === 'STYLE' || parent.tagName === 'TEXTAREA') continue;
        const cur = node.nodeValue;
        if (node.__gpRu === undefined || (node.__gpEn !== undefined && cur !== node.__gpEn && cur !== node.__gpRu)) {
            if (!en || !CYR.test(cur)) { node.__gpRu = undefined; node.__gpEn = undefined; continue; }
            node.__gpRu = cur;
        }
        const next = en ? tr(node.__gpRu) : node.__gpRu;
        node.__gpEn = next;
        if (cur !== next) node.nodeValue = next;
    }
    const els = [root, ...root.querySelectorAll('*')];
    for (const el of els) {
        if (!el.getAttribute) continue;
        const store = el.__gpAttr || (el.__gpAttr = {});
        for (const attr of ATTRS) {
            const cur = el.getAttribute(attr);
            if (cur === null) continue;
            let st = store[attr];
            if (!st || (cur !== st.en && cur !== st.ru)) {
                if (!en || !CYR.test(cur)) { delete store[attr]; continue; }
                st = store[attr] = { ru: cur, en: tr(cur) };
            }
            const target = en ? st.en : st.ru;
            if (cur !== target) el.setAttribute(attr, target);
        }
    }
}

// Следит за динамическими вставками (листы, модалки, тосты внутри телефона)
// и переводит их сразу — иначе всё, что рисуется ПОСЛЕ основного рендера,
// остаётся по-русски.
const _watched = new WeakSet();
export function watchTranslate(root) {
    if (!root || _watched.has(root) || typeof MutationObserver === 'undefined') return;
    _watched.add(root);
    const pending = new Set();
    let raf = 0;
    const flush = () => {
        raf = 0;
        const items = [...pending];
        pending.clear();
        if (lang() !== 'en') return;
        for (const n of items) {
            try { if (n.isConnected) trDom(n); } catch (_e) { /* ignore */ }
        }
    };
    new MutationObserver(muts => {
        for (const m of muts) {
            if (m.type === 'childList') m.addedNodes.forEach(n => { if (n.nodeType === 1 || n.nodeType === 3) pending.add(n); });
            else pending.add(m.target);
        }
        if (pending.size && !raf) raf = requestAnimationFrame(flush);
    }).observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
}

